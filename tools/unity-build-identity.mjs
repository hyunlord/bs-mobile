import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { lstat, readFile } from 'node:fs/promises';
import path from 'node:path';

const roots = ['core/src', 'data', 'unity/Assets', 'unity/Packages', 'unity/ProjectSettings', 'tools', 'Directory.Build.props', 'global.json', '.gitignore', '.gitattributes'];
const hash = bytes => createHash('sha256').update(bytes).digest('hex').toUpperCase();
function git(root, args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', env: { ...process.env, DEVELOPER_DIR: process.env.DEVELOPER_DIR ?? '/Library/Developer/CommandLineTools' } });
}
export async function buildIdentity(root) {
  const commit = git(root, ['rev-parse', '--verify', 'HEAD']).trim();
  assert.match(commit, /^[a-f0-9]{40}$/i, 'Build requires a committed repository identity');
  const names = [...new Set(git(root, ['ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', ...roots]).split('\0').filter(Boolean))].sort();
  const inputs = [];
  for (const name of names) {
    if (/^data\/test\//.test(name) || /^unity\/Assets\/(?:Game\/App\/)?Generated(?:\/|\.meta$)/.test(name) || /^(?:core|tools)\/.*\/(?:bin|obj)\//.test(name)) continue;
    const file = path.join(root, name);
    const stat = await lstat(file).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
    if (!stat) continue;
    assert.ok(stat.isFile() && !stat.isSymbolicLink(), `Build identity requires regular source file: ${name}`);
    inputs.push({ path: name, sha256: hash(await readFile(file)) });
  }
  return {
    commit,
    sourceDirty: git(root, ['status', '--porcelain=v1', '--untracked-files=all', '--', ...roots, ':(exclude)data/test/**']).length > 0,
    sourceHash: hash(JSON.stringify(inputs)),
  };
}
export function identitySource(identity) {
  return `// Generated by tools/prepare-unity.sh. Do not edit.\nnamespace Game.App.Generated\n{\n    public static class BuildIdentity\n    {\n        public const string Commit = "${identity.commit}";\n        public const bool SourceDirty = ${identity.sourceDirty};\n        public const string SourceHash = "${identity.sourceHash}";\n    }\n}\n`;
}
